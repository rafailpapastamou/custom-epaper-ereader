#include "xmlParser.h"

#include <cstring>
#include <utility>

#include "tinyxml2.h"

// --------------------------------------------------
// Internal helpers
// --------------------------------------------------

static const char *localName(const char *name)
{
    if (!name)
        return nullptr;

    const char *colon = strrchr(name, ':');

    return colon ? colon + 1 : name;
}

static bool isBlockElement(const char *name)
{
    name = localName(name);

    if (!name)
        return false;

    static const char *const names[] = {
        "p", "div", "section", "article",
        "blockquote", "li", "ul", "ol",
        "h1", "h2", "h3", "h4", "h5", "h6",
        "br", "tr", "pre", "hr",
        nullptr};

    for (int i = 0; names[i]; ++i)
    {
        if (strcmp(name, names[i]) == 0)
            return true;
    }

    return false;
}

static bool isIgnoredElement(const char *name)
{
    name = localName(name);

    if (!name)
        return false;

    return strcmp(name, "script") == 0 ||
           strcmp(name, "style") == 0 ||
           strcmp(name, "nav") == 0 ||
           strcmp(name, "head") == 0 ||
           strcmp(name, "svg") == 0;
}

// Find an element recursively, ignoring namespace prefixes.
static tinyxml2::XMLElement *findElement(
    tinyxml2::XMLNode *node,
    const char *target)
{
    if (!node)
        return nullptr;

    tinyxml2::XMLElement *element = node->ToElement();

    if (element)
    {
        const char *name = localName(element->Name());

        if (name && strcmp(name, target) == 0)
            return element;
    }

    for (tinyxml2::XMLNode *child = node->FirstChild();
         child;
         child = child->NextSibling())
    {
        tinyxml2::XMLElement *found = findElement(child, target);

        if (found)
            return found;
    }

    return nullptr;
}

// --------------------------------------------------
// XHTML text extraction
// --------------------------------------------------

static void appendTextNode(std::string &out, const char *value)
{
    if (!value)
        return;

    for (const unsigned char *p =
             reinterpret_cast<const unsigned char *>(value);
         *p;
         ++p)
    {
        // Collapse ASCII whitespace.
        if (*p == ' ' || *p == '\t' ||
            *p == '\r' || *p == '\n' || *p == '\f')
        {
            if (!out.empty() && out.back() != ' ')
                out += ' ';
        }
        else
        {
            out += static_cast<char>(*p);
        }
    }
}

static void extractNode(tinyxml2::XMLNode *node, std::string &out)
{
    if (!node)
        return;

    if (node->ToText())
    {
        appendTextNode(out, node->Value());
        return;
    }

    tinyxml2::XMLElement *element = node->ToElement();

    const char *name = element ? element->Name() : nullptr;

    if (isIgnoredElement(name))
        return;

    bool block = isBlockElement(name);

    if (block && !out.empty() && out.back() != '\n')
        out += '\n';

    for (tinyxml2::XMLNode *child = node->FirstChild();
         child;
         child = child->NextSibling())
    {
        extractNode(child, out);
    }

    if (block && !out.empty() && out.back() != '\n')
        out += '\n';
}

// Normalize whitespace generated by XHTML nesting.
// Preserve paragraph breaks but prevent excessive blank lines.
static void normalizeText(std::string &text)
{
    std::string result;
    result.reserve(text.size());

    int consecutiveNewlines = 0;

    for (char c : text)
    {
        if (c == '\r' || c == '\n')
        {
            while (!result.empty() && result.back() == ' ')
                result.pop_back();

            if (++consecutiveNewlines <= 2)
                result += '\n';
        }
        else if (c == ' ' || c == '\t' || c == '\f')
        {
            consecutiveNewlines = 0;

            if (!result.empty() &&
                result.back() != ' ' &&
                result.back() != '\n')
            {
                result += ' ';
            }
        }
        else
        {
            consecutiveNewlines = 0;
            result += c;
        }
    }

    while (!result.empty() &&
           (result.back() == ' ' || result.back() == '\n'))
    {
        result.pop_back();
    }

    size_t start = 0;

    while (start < result.size() &&
           (result[start] == ' ' || result[start] == '\n'))
    {
        ++start;
    }

    if (start > 0)
        result.erase(0, start);

    text = std::move(result);
}

// --------------------------------------------------
// Public API
// --------------------------------------------------

bool xmlExtractText(const std::string &xhtml, std::string &outText)
{
    outText.clear();

    tinyxml2::XMLDocument doc;

    if (doc.Parse(xhtml.c_str(), xhtml.size()) != tinyxml2::XML_SUCCESS)
        return false;

    tinyxml2::XMLElement *root = doc.RootElement();

    if (!root)
        return false;

    // Locate body, supporting namespace-prefixed XHTML.
    tinyxml2::XMLElement *body = findElement(root, "body");

    extractNode(
        body ? static_cast<tinyxml2::XMLNode *>(body)
             : static_cast<tinyxml2::XMLNode *>(root),
        outText);

    normalizeText(outText);

    return true;
}
